// Turn the summary into: an HTML report, a Slack-format message and an email payload.
const s = $input.first().json;
const cfg = $('Settings').first().json;
const fmt = (n, c) => (c ? c + ' ' : '') + n.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
const esc = t => String(t).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const reportFile = `${cfg.report_dir}/report_${s.run_date}.html`;
const badFile = `${cfg.report_dir}/bad_rows_${s.run_date}.csv`;
const validFile = `${cfg.report_dir}/valid_rows_${s.run_date}.csv`;
const status = s.invalid > 0 ? 'attention' : 'clean';
const headline = s.invalid > 0
  ? `${s.invalid} of ${s.rows} rows need attention (${s.invalid_pct}%)`
  : `All ${s.rows} rows passed validation`;
const MAX_LISTED = 10;
const listed = s.bad_rows.slice(0, MAX_LISTED);
const more = s.bad_rows.length - listed.length;
const labelOf = Object.fromEntries(s.invalid_by_reason.map(x => [x.reason, x.label]));

// ---------- HTML report ----------
const th = h => `<th>${h}</th>`;
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8">
<title>Daily orders report ${s.run_date}</title>
<style>
 body{font:15px/1.5 -apple-system,Segoe UI,Roboto,sans-serif;background:#f4f6f9;color:#1d2433;margin:0;padding:32px}
 .wrap{max-width:980px;margin:auto}
 h1{font-size:24px;margin:0 0 4px} .sub{color:#667085;margin-bottom:22px}
 .kpis{display:grid;grid-template-columns:repeat(4,1fr);gap:14px;margin-bottom:18px}
 .kpi{background:#fff;border-radius:10px;padding:14px 18px;box-shadow:0 1px 3px rgba(16,24,40,.1)}
 .kpi b{display:block;font-size:28px} .kpi span{color:#667085;font-size:13px}
 .kpi.bad b{color:#c4321c} .kpi.ok b{color:#1b7f4b}
 .grid{display:grid;grid-template-columns:1fr 1fr;gap:14px}
 .card{background:#fff;border-radius:10px;padding:16px 20px;box-shadow:0 1px 3px rgba(16,24,40,.1);margin-bottom:14px}
 .card h2{font-size:15px;margin:0 0 10px;text-transform:uppercase;letter-spacing:.04em;color:#475467}
 table{border-collapse:collapse;width:100%} th,td{text-align:left;padding:6px 8px;border-bottom:1px solid #eef0f4;font-size:14px}
 th{color:#667085;font-weight:600} td.n,th.n{text-align:right;font-variant-numeric:tabular-nums}
 code{background:#eef0f4;border-radius:4px;padding:1px 6px;font-size:13px}
 .foot{color:#98a2b3;font-size:12px;margin-top:18px}
</style></head><body><div class="wrap">
<h1>${esc(s.company)} - daily orders report</h1>
<div class="sub">Source <code>${esc(s.source_file)}</code> &middot; order dates ${s.order_date_from} to ${s.order_date_to} &middot; generated ${s.run_at.slice(0, 16).replace('T', ' ')} UTC</div>
<div class="kpis">
 <div class="kpi"><b>${s.rows}</b><span>rows read</span></div>
 <div class="kpi ok"><b>${s.valid}</b><span>valid</span></div>
 <div class="kpi ${s.invalid ? 'bad' : 'ok'}"><b>${s.invalid}</b><span>invalid (${s.invalid_pct}%)</span></div>
 <div class="kpi"><b>${s.revenue_totals.map(t => fmt(t.revenue, t.currency)).join('<br>') || '-'}</b><span>net revenue (valid, excl. ${s.refunded_excluded} refunded)</span></div>
</div>
<div class="grid">
 <div class="card"><h2>Revenue by region</h2><table><tr>${th('Region')}${th('Cur.')}<th class="n">Orders</th><th class="n">Revenue</th></tr>
 ${s.revenue_by_region.map(x => `<tr><td>${x.region}</td><td>${x.currency}</td><td class="n">${x.orders}</td><td class="n">${fmt(x.revenue)}</td></tr>`).join('')}</table></div>
 <div class="card"><h2>Top SKUs by units</h2><table><tr>${th('SKU')}<th class="n">Orders</th><th class="n">Units</th></tr>
 ${s.top_skus.map(x => `<tr><td><code>${x.sku}</code></td><td class="n">${x.orders}</td><td class="n">${x.units}</td></tr>`).join('')}</table></div>
</div>
<div class="card"><h2>Invalid rows by reason</h2><table><tr>${th('Reason')}${th('Rule')}<th class="n">Rows</th></tr>
 ${s.invalid_by_reason.map(x => `<tr><td><code>${x.reason}</code></td><td>${esc(x.label)}</td><td class="n">${x.count}</td></tr>`).join('') || '<tr><td colspan="3">None</td></tr>'}</table></div>
<div class="card"><h2>Bad rows (CSV line / order / reason)</h2><table><tr><th class="n">Line</th>${th('Order')}${th('Reason')}</tr>
 ${s.bad_rows.map(x => `<tr><td class="n">${x.csv_line}</td><td>${esc(x.order_id || '(blank)')}</td><td><code>${x.reason}</code></td></tr>`).join('') || '<tr><td colspan="3">None</td></tr>'}</table></div>
<div class="foot">Synthetic demo data. Full list: <code>bad_rows_${s.run_date}.csv</code>. Generated by an n8n workflow.</div>
</div></body></html>`;

// ---------- Slack message (Block Kit + plain-text fallback) ----------
const pad = (t, n) => String(t).padEnd(n);
const regionLines = s.revenue_by_region.map(x => `${pad(x.region, 6)} ${x.currency}  ${fmt(x.revenue).padStart(12)}  (${x.orders} orders)`).join('\n');
const skuLines = s.top_skus.map((x, i) => `${i + 1}. ${x.sku} - ${x.units} units`).join('\n');
const reasonLines = s.invalid_by_reason.map(x => `- *${x.count}* x ${x.label} (\`${x.reason}\`)`).join('\n');
const badLines = listed.map(x => `line ${x.csv_line} - \`${x.order_id || 'blank id'}\` - ${labelOf[x.reason] || x.reason}`).join('\n')
  + (more > 0 ? `\n_...and ${more} more in the CSV_` : '');
const slack = {
  text: `Daily orders report ${s.run_date}: ${headline}`,
  blocks: [
    { type: 'header', text: { type: 'plain_text', text: `:warning: Daily orders report - ${s.run_date}`, emoji: true } },
    { type: 'section', text: { type: 'mrkdwn', text: `*${headline}* in \`${s.source_file}\`` } },
    { type: 'section', fields: [
      { type: 'mrkdwn', text: `*Rows read*\n${s.rows}` },
      { type: 'mrkdwn', text: `*Valid*\n${s.valid}` },
      { type: 'mrkdwn', text: `*Invalid*\n${s.invalid} (${s.invalid_pct}%)` },
      { type: 'mrkdwn', text: `*Net revenue*\n${s.revenue_totals.map(t => fmt(t.revenue, t.currency)).join(' + ')}` },
    ] },
    { type: 'divider' },
    { type: 'section', text: { type: 'mrkdwn', text: `*Invalid rows by reason*\n${reasonLines}` } },
    { type: 'section', text: { type: 'mrkdwn', text: `*First ${listed.length} bad rows*\n${badLines}` } },
    { type: 'section', text: { type: 'mrkdwn', text: `*Revenue by region*\n\`\`\`${regionLines}\`\`\`` } },
    { type: 'section', text: { type: 'mrkdwn', text: `*Top SKUs*\n${skuLines}` } },
    { type: 'context', elements: [{ type: 'mrkdwn', text: `Full list: \`bad_rows_${s.run_date}.csv\` - report: \`report_${s.run_date}.html\` - demo run, mock webhook` }] },
  ],
};

// ---------- Email payload (generic transactional-email API shape) ----------
const text = [
  `${s.company} - daily orders report ${s.run_date}`, '', headline, '',
  `Rows read: ${s.rows}   Valid: ${s.valid}   Invalid: ${s.invalid}`, '',
  'Invalid rows by reason:', ...s.invalid_by_reason.map(x => `  ${x.count} x ${x.label} (${x.reason})`), '',
  'Bad rows:', ...listed.map(x => `  line ${x.csv_line}  ${x.order_id || '(blank)'}  ${x.reason}`),
  more > 0 ? `  ...and ${more} more (see attached CSV)` : '', '',
  'Attachments: bad_rows_' + s.run_date + '.csv, report_' + s.run_date + '.html',
].join('\n');
const email = {
  from: cfg.alert_email_from, to: [cfg.alert_email_to],
  subject: `[${s.company}] Orders ${s.run_date}: ${s.invalid} of ${s.rows} rows need attention`,
  text,
  html: `<h2>${esc(s.company)} - daily orders report ${s.run_date}</h2><p><b>${esc(headline)}</b></p><ul>`
    + s.invalid_by_reason.map(x => `<li>${x.count} x ${esc(x.label)} (<code>${x.reason}</code>)</li>`).join('') + '</ul>',
  attachments: [{ filename: `bad_rows_${s.run_date}.csv`, path: badFile }, { filename: `report_${s.run_date}.html`, path: reportFile }],
};

return [{ json: { ...s, status, headline, html, slack, email, files: { reportFile, badFile, validFile } } }];
